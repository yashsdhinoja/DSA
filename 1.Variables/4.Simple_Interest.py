# Calculate Simple Interest using Variable.

print("Calculate Simple Interest")
principal = 12000
time_in_year = 3.7
Interest_Rate = 9.3
Simple_Interest = principal * time_in_year * Interest_Rate / 100
print(f"principal : {principal} \ntime_in_year : {time_in_year} \nInterest_Rate : {Interest_Rate} \nSimple Interest : {Simple_Interest}")